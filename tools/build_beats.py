"""Scan the beats folder, convert to MP3, write js/beats.js.

Usage: python -I tools/build_beats.py [source_dir]
Re-running skips files that are already converted.
"""
import json
import re
import struct
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "Desktop" / "best"
OUT = ROOT / "audio"
FF_BIN = next((ROOT / "tools" / "ffmpeg").glob("*/bin"))
FFMPEG, FFPROBE = str(FF_BIN / "ffmpeg.exe"), str(FF_BIN / "ffprobe.exe")

# Not own material / not audio -> never published.
EXCLUDE = re.compile(r"soundloadmate", re.I)
# Suffixes that mark alternate versions of the same beat.
VARIANT = re.compile(r"(?:\s*(instrumental|instrnt|instr|inst|vocals?|ext|maxi)|_\d+)+$", re.I)
LABELS = {"instrumental": "instrumental", "instrnt": "instrumental", "instr": "instrumental",
          "inst": "instrumental", "vocals": "vocals", "vocal": "vocals", "1": "alt"}
PEAKS = 120


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "beat"


def parse(name):
    # "(1)", "(vocal)" -> variant tags
    tags = [t.lower() for t in re.findall(r"\((.*?)\)", name)]
    name = re.sub(r"\(.*?\)", "", name).strip()
    bpm = None
    m = re.match(r"^(\d{2,4})\s*(.*)$", name)
    if m:
        bpm, name = int(m.group(1)[:3]), m.group(2)  # "1220EISBLOCK" -> 122
    else:  # BPM at the end or inside: "gasse110", "sad140jumop", "instrOPIUM115"
        m = re.search(r"(?<!\d)(5\d|[6-9]\d|1\d\d|200)(?!\d)", name)
        if m:
            bpm = int(m.group(1))
            name = (name[: m.start()] + " " + name[m.end():]).strip()
    name = name.strip(" _-;!") or "untitled"
    if re.match(r"^(instr|ins)(?=[\sA-Z0-9])", name) and len(name) > 6:  # "instrOPIUM", "ins137CHRO"
        name, tags = re.sub(r"^(instr|ins)\s*", "", name), tags + ["inst"]
    vm = VARIANT.search(name)
    base = name[: vm.start()].strip(" _-") if vm and vm.start() > 0 else name
    parts = [p for p in re.split(r"[\s_]+", name[len(base):].lower()) if p] + tags
    label = " ".join(LABELS.get(p, f"v{p}" if p.isdigit() else p) for p in parts) or "main"
    return bpm, base.strip(" _-;!"), label


def convert(src: Path, dst: Path):
    if not dst.exists():
        subprocess.run([FFMPEG, "-v", "error", "-y", "-i", str(src), "-vn", "-ac", "2",
                        "-b:a", "192k", str(dst)], check=True)
    dur = float(subprocess.run([FFPROBE, "-v", "error", "-show_entries", "format=duration",
                                "-of", "csv=p=0", str(dst)], capture_output=True, text=True).stdout or 0)
    raw = subprocess.run([FFMPEG, "-v", "error", "-i", str(dst), "-ac", "1", "-ar", "2000",
                          "-f", "s16le", "-"], capture_output=True).stdout
    n = len(raw) // 2
    samples = struct.unpack(f"<{n}h", raw[: n * 2]) if n else ()
    step = max(1, n // PEAKS)
    peaks = [max((abs(x) for x in samples[i:i + step]), default=0) for i in range(0, step * PEAKS, step)]
    top = max(peaks) or 1
    return round(dur, 1), [round(p / top, 2) for p in peaks]


def main():
    files = sorted(p for p in SRC.iterdir()
                   if p.suffix.lower() in (".wav", ".mp3") and not EXCLUDE.search(p.name))
    jobs = []
    for p in files:
        bpm, base, label = parse(p.stem)
        jobs.append((p, OUT / f"{slug(p.stem)}.mp3", bpm, base, label))

    with ThreadPoolExecutor(max_workers=6) as ex:
        results = list(ex.map(lambda j: convert(j[0], j[1]), jobs))

    beats = {}
    for (p, dst, bpm, base, label), (dur, peaks) in zip(jobs, results):
        key = slug(base)
        b = beats.setdefault(key, {"id": key, "title": base.upper(), "bpm": bpm, "versions": []})
        b["versions"].append({"label": label, "file": f"audio/{dst.name}", "duration": dur, "peaks": peaks})
        print(f"  {p.name} -> {key} [{label}]")
    for b in beats.values():
        b["versions"].sort(key=lambda v: v["label"] != "main")
        b["duration"] = b["versions"][0]["duration"]

    data = sorted(beats.values(), key=lambda b: (b["bpm"] or 0, b["title"]))
    (ROOT / "js" / "beats.js").write_text(
        "// generated by tools/build_beats.py\nexport const BEATS = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    print(f"{len(data)} beats, {len(jobs)} files")


if __name__ == "__main__":
    main()
